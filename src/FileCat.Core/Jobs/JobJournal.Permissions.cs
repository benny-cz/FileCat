using System.Security.Cryptography;
using System.Globalization;
using System.Text;
using System.Text.Json.Nodes;
using FileCat.Core.Permissions;

namespace FileCat.Core.Jobs;

/// <summary>The native store keeps the private directory and exact journal file under verification until close.</summary>
internal sealed record PermissionJournalFile(string Path, FileStream Stream, Action Verify, IDisposable Owner);

internal static class PermissionJournalNames
{
    internal const string Directory = "permissions";
    internal static string Name(DateTime utc, Guid id) => $"permissions-{utc.ToString("yyyyMMddHHmmss", CultureInfo.InvariantCulture)}-{id:N}.fcj";
    internal static bool TryParse(string name, out DateTime utc, out Guid id)
    {
        utc = default;
        id = default;
        return name.Length == 63 && name.StartsWith("permissions-", StringComparison.Ordinal) && name[26] == '-' &&
            name.EndsWith(".fcj", StringComparison.Ordinal) && DateTime.TryParseExact(name.AsSpan(12, 14), "yyyyMMddHHmmss",
                CultureInfo.InvariantCulture, DateTimeStyles.AssumeUniversal | DateTimeStyles.AdjustToUniversal, out utc) &&
            Guid.TryParseExact(name.AsSpan(27, 32), "N", out id) && id != Guid.Empty && name == Name(utc, id);
    }

    internal static void Require(string name)
    {
        if (!TryParse(name, out _, out _)) throw new ArgumentException("The permissions journal name must be generated by FileCat.", nameof(name));
    }

    internal static string IdentityDigest(PermissionIdentity id) => Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(
        FormattableString.Invariant($"{id.Kind}\0{id.Object}\0{id.MountInstance}\0{id.Authority.Kind}\0{id.Authority.Id}\0{id.Authority.Generation}"))));
}

public sealed partial class JobJournal
{
    internal const int PermissionJournalVersion = 1;
    internal const int PermissionRecordLimit = 8 * 1024 * 1024;
    private Action? _verifyPermissionFile;
    private IDisposable? _permissionFileOwner;
    private Guid _permissionJob;
    private bool _permissionFaulted;
    private int _pendingPermissionStep;

    internal static JobJournal CreatePermissions(Job job, Func<string, CancellationToken, PermissionJournalFile> create)
    {
        var operation = job.PermissionOperation ?? throw new InvalidOperationException("The permissions review no longer owns its subjects.");
        string leaf = PermissionJournalNames.Name(job.CreatedUtc, job.Id);
        var file = create(leaf, job.Token);
        var journal = new JobJournal(file.Path, file.Stream)
        {
            _permissionJob = job.Id, _verifyPermissionFile = file.Verify, _permissionFileOwner = file.Owner
        };
        try
        {
            var sources = new JsonArray();
            int sampledBytes = 0;
            foreach (var target in operation.Targets.Where(target => target.ServerPath is null).Take(64))
            {
                var path = JsonValue.Create(target.Subject.RawLocator)!;
                int bytes = Encoding.UTF8.GetByteCount(path.ToJsonString());
                if (sampledBytes + bytes + 1 > 1024 * 1024) break;
                sampledBytes += bytes + 1;
                sources.Add(path);
            }
            var begin = new JsonObject
            {
                ["t"] = "begin", ["kind"] = nameof(JobKind.Permissions), ["title"] = "Permissions and ownership",
                ["id"] = job.Id.ToString("N"), ["created"] = job.CreatedUtc.ToString("O"),
                ["version"] = PermissionJournalVersion, ["scope"] = operation.Scope.ToString(),
                ["sourceCount"] = operation.Targets.Length, ["sources"] = sources
            };
            if (operation.UsesServerPath) begin["serverPath"] = true;
            if (operation.Tree is { Summary: var tree })
                begin["tree"] = new JsonObject
                {
                    ["roots"] = tree.Roots, ["inaccessible"] = tree.InaccessibleBranches,
                    ["excluded"] = tree.ExcludedEntries, ["aliases"] = tree.Aliases, ["protected"] = tree.ProtectedEntries
                };
            if (operation.TreeSource is { } source)
            {
                begin["template"] = source.Subject.RawLocator;
                begin["templateRevision"] = source.Revision.Digest;
            }
            journal.WritePermission(begin);
            return journal;
        }
        catch { journal.Dispose(); throw; }
    }

    internal int PermissionIntent(int target, ReviewedPermissionTarget reviewed, ReviewedPermissionComponent component)
    {
        int step = ++_step;
        if (_pendingPermissionStep != 0) throw new IOException("The previous permissions call still needs an outcome.");
        string identity = reviewed.ServerPath?.Digest ?? PermissionJournalNames.IdentityDigest(reviewed.Binding!.Identity);
        WritePermission(new JsonObject
        {
            ["t"] = "permission-intent", ["v"] = PermissionJournalVersion, ["id"] = _permissionJob.ToString("N"),
            ["n"] = step, ["target"] = target, ["identity"] = identity, ["section"] = (int)component.Change.Section,
            ["before"] = component.Before.Digest, ["expected"] = component.Expected.Digest,
            ["modeBits"] = component.Change is ChangePermissionMode mode ? mode.Bits & mode.TouchedBits : null,
            ["modeTouched"] = component.Change is ChangePermissionMode touched ? (int)touched.TouchedBits : null,
            ["flagBits"] = component.Change is ChangePermissionFlags flags ? flags.Bits & flags.TouchedBits : null,
            ["flagTouched"] = component.Change is ChangePermissionFlags mask ? mask.TouchedBits : null
        });
        _pendingPermissionStep = step;
        return step;
    }

    internal void PermissionOutcome(int step, PermissionComponentResult result)
    {
        if (_pendingPermissionStep != step) throw new InvalidOperationException("This permissions outcome has no matching live intent.");
        if (result.Verdict is PermissionVerdict.Uncertain or PermissionVerdict.Partial) RequireRecovery();
        WritePermission(new JsonObject
        {
            ["t"] = "permission-outcome", ["v"] = PermissionJournalVersion, ["id"] = _permissionJob.ToString("N"),
            ["n"] = step, ["verdict"] = result.Verdict.ToString(), ["verification"] = result.Verification.ToString(),
            ["observed"] = result.ObservedDigest, ["error"] = result.NativeError
        });
        _pendingPermissionStep = 0;
    }

    internal void PermissionObject(int target, PermissionVerdict verdict, PermissionRevision expected, PermissionRevision? observed)
    {
        if (verdict is PermissionVerdict.Uncertain or PermissionVerdict.Partial) RequireRecovery();
        WritePermission(new JsonObject
        {
            ["t"] = "permission-object", ["v"] = PermissionJournalVersion, ["id"] = _permissionJob.ToString("N"),
            ["target"] = target, ["verdict"] = verdict.ToString(), ["expected"] = expected.Digest, ["observed"] = observed?.Digest
        });
    }

    private void WritePermission(JsonObject record)
    {
        lock (_lock)
        {
            ObjectDisposedException.ThrowIf(_disposed, this);
            if (_verifyPermissionFile is null || _permissionFaulted)
                throw new IOException("Private permissions history is unavailable.");
            try
            {
                // Include headroom for both a maximum bounded record and the final journal record.
                if (_stream.Length >= PermissionRecordLimit - 16 * 1024)
                    throw new IOException("The permissions journal reached its durable record budget. Review a smaller batch.");
                _verifyPermissionFile();
                Write(record, sync: true);
                _verifyPermissionFile();
            }
            catch
            {
                _permissionFaulted = true;
                RequireRecovery();
                throw;
            }
        }
    }

    internal static IEnumerable<JournalRecord> ReadPermissionRecords(Stream stream, Action damaged)
    {
        if (stream.Length > PermissionRecordLimit) throw new IOException("The permissions history exceeds its read budget.");
        return ReadRecords(ReadBoundedLines(stream, requireTerminated: true), damaged);
    }
}
